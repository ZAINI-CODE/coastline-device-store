    await db.exec(await readFile("supabase/migrations/004_media_and_contact.sql", "utf8"));
    await db.exec(await readFile("supabase/migrations/005_refunds.sql", "utf8"));
    await db.exec(await readFile("supabase/migrations/006_product_attributes.sql", "utf8"));
