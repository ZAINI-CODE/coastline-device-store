    const place = async (items, addr = address, key = "33333333-3333-4333-8333-333333333333", method = "paypal") => (await db.query("select place_order($1::jsonb,$2::jsonb,$3,$4,$5) as id", [JSON.stringify(items), JSON.stringify(addr), shipping, method, key])).rows[0].id;
    await assert.rejects(() => place(null), /Invalid checkout/);
    await assert.rejects(() => place([{ variant_id: v, quantity: -1 }]), /Invalid quantities/);
    await assert.rejects(() => place([{ variant_id: v, quantity: 1 }], {}), /address/);
    await assert.rejects(() => place([{ variant_id: v, quantity: 4 }]), /inventory/);
    const id = await place([{ variant_id: v, quantity: 2, price_cents: 1 }]);
    const order = (await db.query("select * from orders")).rows[0];
    assert.equal(order.total_cents, 21730);
    assert.equal(order.subtotal_cents, 2e4);
    assert.equal(await place([{ variant_id: v, quantity: 2 }]), id);
    assert.equal((await db.query("select quantity from inventory")).rows[0].quantity, 1);
    await assert.rejects(() => db.query(`update orders set payment_status='paid' where id=$1`, [id]), /permission denied/);
    await db.exec("reset role");
    await db.query(`select set_config('request.uid',$1,false)`, [b]);
    await db.exec("set role authenticated");
    assert.equal((await db.query("select * from orders")).rows.length, 0);
    assert.equal((await db.query("select * from order_items")).rows.length, 0);
    assert.equal((await db.query("select * from payments")).rows.length, 0);
    await assert.rejects(() => db.query("insert into admin_members values($1)", [b]), /row-level security|permission denied/);
    await assert.rejects(() => db.query(`select admin_order($1,'verify_zelle','fake-reference','')`, [id]), /MFA/);
    await db.exec("reset role");
    await db.query(`select confirm_payment($1,'capture-test',21730,'USD',null)`, [id]);
    await db.query(`select confirm_payment($1,'capture-test',21730,'USD',null)`, [id]);
    await assert.rejects(() => db.query(`select confirm_payment($1,'capture-test',1,'USD',null)`, [id]), /mismatch/);
    await db.query("select release_order($1)", [id]);
    assert.equal((await db.query("select quantity from inventory")).rows[0].quantity, 1);
    await db.query(`select set_config('request.uid',$1,false)`, [a]);
    await db.exec("set role authenticated");
    await db.query(`select submit_review($1,5,'A test review only','Test')`, [p]);
    assert.equal((await db.query("select approved from reviews")).rows[0].approved, false);
    await db.exec("reset role");
    await db.query(`insert into admin_members values($1)`, [a]);
    await db.exec("set role authenticated");
    assert.equal((await db.query("select is_admin() as allowed")).rows[0].allowed, false);
    await db.exec(`select set_config('request.aal','aal2',false)`);
    assert.equal((await db.query("select is_admin() as allowed")).rows[0].allowed, true);
    await db.exec("reset role");
    await db.query("update inventory set quantity=10 where variant_id=$1", [v]);
    const promo = (await db.query(`insert into promotions(name,kind,minimum_quantity,percent_basis_points,discount_cents,starts_at,ends_at,active) values('TEST BUNDLE','bundle',2,0,2500,now()-interval '1 day',now()+interval '1 day',true) returning id`)).rows[0].id;
    await db.query("insert into promotion_products values($1,$2)", [promo, p]);
    await db.exec("set role authenticated");
    const discounted = await place([{ variant_id: v, quantity: 2 }], address, "44444444-4444-4444-8444-444444444444");
    const d = (await db.query("select * from orders where id=$1", [discounted])).rows[0];
    assert.equal(d.discount_cents, 2500);
    assert.equal(d.total_cents, 19080);
    assert.equal((await db.query("select sum(discount_cents)::int as n from order_items where order_id=$1", [discounted])).rows[0].n, 2500);
    await db.query(`select admin_order($1,'cancel','','')`, [discounted]);
    await db.exec("reset role");
    const afterCancel = (await db.query("select quantity from inventory")).rows[0].quantity;
    await db.query("select release_order($1)", [discounted]);
    assert.equal((await db.query("select quantity from inventory")).rows[0].quantity, afterCancel);
    await db.exec("set role authenticated");
    await db.query(`select send_contact('Test subject','This is a private test message')`);
    await db.exec("reset role");
    await db.query(`select set_config('request.uid',$1,false)`, [b]);
    await db.exec(`select set_config('request.aal','aal1',false);set role authenticated`);
    assert.equal((await db.query("select * from contact_messages")).rows.length, 0);
    await db.exec("reset role");
    await db.query("update store_settings set checkout_enabled=false");
    await db.exec("set role authenticated");
    await assert.rejects(() => place([{ variant_id: v, quantity: 1 }], address, "55555555-5555-4555-8555-555555555555"), /owner approval/);
    await assert.rejects(() => db.query("select request_full_refund($1,null)", [id]), /MFA/);
    await db.exec("reset role");
    await db.query("select set_config('request.uid',$1,false)", [a]);
    await db.exec("select set_config('request.aal','aal2',false);set role authenticated");
    const refund = (await db.query("select request_full_refund($1,null) as id", [id])).rows[0].id;
    assert.equal((await db.query("select request_full_refund($1,null) as id", [id])).rows[0].id, refund);
    await db.exec("reset role");
    await assert.rejects(() => db.query("select finish_paypal_refund($1,'refund-test',1,'USD',true)", [refund]), /mismatch/);
    await assert.rejects(() => db.query("select finish_paypal_refund($1,null,null,null,true)", [refund]), /proof required/);
    await db.query("select finish_paypal_refund($1,'refund-test',21730,'USD',false)", [refund]);
    await assert.rejects(() => db.query("select finish_paypal_refund($1,'changed-refund',21730,'USD',true)", [refund]), /identity mismatch/);
    await db.query("select finish_paypal_refund($1,'refund-test',21730,'USD',true)", [refund]);
    await db.query("select finish_paypal_refund($1,'refund-test',21730,'USD',true)", [refund]);
    assert.equal((await db.query("select payment_status from orders where id=$1", [id])).rows[0].payment_status, "refunded");
    const stockAfterRefund = (await db.query("select quantity from inventory")).rows[0].quantity;
    await db.query("select confirm_payment($1,'capture-test',21730,'USD',null)", [id]);
    assert.equal((await db.query("select payment_status from orders where id=$1", [id])).rows[0].payment_status, "refunded");
    await db.query("select release_order($1)", [id]);
    assert.equal((await db.query("select quantity from inventory")).rows[0].quantity, stockAfterRefund);
    await assert.rejects(() => db.query("select confirm_payment($1,null,21730,'USD',null)", [id]), /mismatch/);
    await db.query("update store_settings set checkout_enabled=true");
    await db.exec("set role authenticated");
    const processing = await place([{ variant_id: v, quantity: 1 }], address, "66666666-6666-4666-8666-666666666666");
    await db.exec("reset role");
    await db.query("select begin_capture($1)", [processing]);
    await db.query("update orders set expires_at=now()-interval '1 minute' where id=$1", [processing]);
    const reservedStock = (await db.query("select quantity from inventory")).rows[0].quantity;
    await db.query("select expire_reservations()");
    assert.equal((await db.query("select quantity from inventory")).rows[0].quantity, reservedStock);
    await db.exec("set role authenticated");
    await assert.rejects(() => db.query("select admin_order($1,'cancel','','')", [processing]), /Reconcile/);
    const pending = await place([{ variant_id: v, quantity: 1 }], address, "77777777-7777-4777-8777-777777777777");
