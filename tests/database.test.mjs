    await db.query("update orders set expires_at=now()-interval '1 minute' where id=$1", [pending]);
    await db.query("select expire_reservations()");
    assert.equal((await db.query("select quantity from inventory")).rows[0].quantity, reservedStock);
    await db.query("select expire_reservations()");
    assert.equal((await db.query("select quantity from inventory")).rows[0].quantity, reservedStock);
    await db.exec("set role authenticated");
    const summary = (await db.query("select admin_store_summary() as data")).rows[0].data;
    assert.equal(summary.products, 1);
    assert.equal(summary.captured_cents, 21730);
    assert.equal(summary.refunded_cents, 21730);
