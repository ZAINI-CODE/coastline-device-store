    assert.equal((await db.query('select * from claim_order_emails($1)',[a])).rows.length,0);
    await db.exec('reset role; set role authenticated');
    await assert.rejects(() => db.query('select request_full_refund($1,null)',[zelle]), /bank refund reference/);
