    await db.query("insert into inventory values($1,3)", [v]);
    const shipping = (await db.query(`insert into shipping_rules(country,state,method,price_cents,tax_basis_points,approved,delivery_description) values('US','FL','Test',500,600,true,'Test only') returning id`)).rows[0].id;
