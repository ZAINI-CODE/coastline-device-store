    await db.exec(await readFile("supabase/migrations/010_reservation_limits.sql", "utf8"));
    await db.exec(await readFile("supabase/migrations/011_application_privileges.sql", "utf8"));
    await db.exec(await readFile("supabase/migrations/018_order_email_outbox.sql", "utf8"));
    const a = "11111111-1111-4111-8111-111111111111", b = "22222222-2222-4222-8222-222222222222";
    await db.query("insert into auth.users values($1),($2)", [a, b]);
    const p = (await db.query(`insert into products(name,brand,model,published,verification_source,verified_at) values('TEST ONLY','Test','T',true,'https://example.com/test',now()) returning id`)).rows[0].id;
